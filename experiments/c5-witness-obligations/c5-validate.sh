#!/bin/bash
# Pre-run validation of the C5 harness. This is a GATE, not a transcript: it
# asserts the expected exit status of every case and itself exits non-zero if
# any case disagrees. The first amendment's validation was prose, and prose let
# two mismatched expectations sit in the record as if they had passed.
#
# Every capture case gets its OWN freshly materialised subject; a leftover ref
# from a previous case made the first round's T4/T4b results unreadable.
#
#   c5-validate.sh <workdir>            -> writes prerun-validation.txt
set -u
HERE=$(cd "$(dirname "$0")" && pwd)
CTRL=$(cd "$HERE/../.." && pwd)
W=${1:?usage: c5-validate.sh <workdir>}
X=f01592b0f0828605ed254047fc064f41dacc78f2
OUT="$HERE/prerun-validation.txt"
rm -rf "$W"; mkdir -p "$W"
PASS=0; FAIL=0; N=0

fresh() { # fresh <name> -> a subject materialised by the frozen procedure
  local d="$W/subj-$1"
  git -C "$CTRL" tag -f c5-boundary "$X" >/dev/null 2>&1
  git clone -q --depth 1 --no-tags --single-branch --branch c5-boundary "file://$CTRL" "$d" 2>/dev/null
  git -C "$CTRL" tag -d c5-boundary >/dev/null 2>&1
  git -C "$d" remote remove origin >/dev/null 2>&1
  git -C "$d" checkout -qB main "$X"   # the clone already carries refs/tags/c5-boundary
  echo "$d"
}
commit_on() { # commit_on <dir> <branch> <n> -> n commits on a branch off X
  git -C "$1" checkout -q -B "$2" "$X"
  for i in $(seq 1 "$3"); do
    echo "probe $i" > "$1/.c5probe$i"
    git -C "$1" add ".c5probe$i"
    git -C "$1" -c user.email=v@v -c user.name=v commit -qm "probe $i"
  done
  git -C "$1" checkout -q main
}
check() { # check <id> <expected-rc> <description> -- then the command
  local id=$1 want=$2 desc=$3; shift 3
  local rc=0; "$@" >>"$W/raw.txt" 2>&1 || rc=$?
  N=$((N+1))
  if [ "$rc" = "$want" ]; then PASS=$((PASS+1)); echo "PASS  $id  rc=$rc (expected $want)  $desc" >> "$OUT"
  else FAIL=$((FAIL+1)); echo "FAIL  $id  rc=$rc (EXPECTED $want)  $desc" >> "$OUT"; fi
}

{ echo "C5 pre-run harness validation"
  echo "generated by c5-validate.sh; every case asserts its exit status"
  echo "capture sha256 $(sha256sum "$HERE/c5-capture.sh" | cut -d' ' -f1)"
  echo "closure sha256 $(sha256sum "$HERE/c5-closure.sh" | cut -d' ' -f1)"
  echo "extract sha256 $(sha256sum "$HERE/c5-extract.py" | cut -d' ' -f1)"
  echo; echo "== capture cases (isolation gate) =="; } > "$OUT"

CAP="$HERE/c5-capture.sh"
d=$(fresh c1); check C1 0 "clean subject, start" bash "$CAP" "$W/c1.txt" start "$d" "$X" ""
d=$(fresh c2); git -C "$d" branch sensei-code/task-1 "$X"
               check C2 1 "candidate-shaped ref present at START" bash "$CAP" "$W/c2.txt" start "$d" "$X" ""
d=$(fresh c3); commit_on "$d" main 1
               check C3 1 "HEAD is not X (the fail-open counter path this amendment closes)" bash "$CAP" "$W/c3.txt" start "$d" "$X" ""
d=$(fresh c4); commit_on "$d" sensei-code/task-1 1
               check C4 1 "candidate ref exists but is not the one the run reported" bash "$CAP" "$W/c4.txt" end "$d" "$X" refs/heads/sensei-code/task-999
d=$(fresh c5); git -C "$d" branch sensei-code/task-1 "$X"
               check C5 0 "the reported candidate ref names X ITSELF -- permitted, annotated, no candidate commit" bash "$CAP" "$W/c5.txt" end "$d" "$X" refs/heads/sensei-code/task-1
d=$(fresh c6); commit_on "$d" sensei-code/task-1 1
               check C6 0 "the reported candidate ref's first parent is exactly X" bash "$CAP" "$W/c6.txt" end "$d" "$X" refs/heads/sensei-code/task-1
d=$(fresh c7); commit_on "$d" sensei-code/task-1 2
               check C7 1 "candidate is two commits beyond X (first parent is not X)" bash "$CAP" "$W/c7.txt" end "$d" "$X" refs/heads/sensei-code/task-1
d=$(fresh c8); git -C "$d" remote add origin "file://$CTRL"
               check C8 1 "a remote is present" bash "$CAP" "$W/c8.txt" start "$d" "$X" ""
d=$(fresh c9); echo "/nonexistent/objects" > "$d/.git/objects/info/alternates"
               check C9 1 "an alternates file is present" bash "$CAP" "$W/c9.txt" start "$d" "$X" ""
d=$(fresh c10); git -C "$d" branch scratch "$X"
               check C10 1 "a ref outside the frozen table" bash "$CAP" "$W/c10.txt" start "$d" "$X" ""

echo >> "$OUT"; echo "== closure cases (instrument gate) ==" >> "$OUT"
CLO="$HERE/c5-closure.sh"; R="$W/gate"; SERV_OK="pid 1 | exe /x | sha256 aa"
mk_start() { rm -rf "$R"; mkdir -p "$R"
  { echo "governor commit (source) $X"; echo "governor binary path /g"; echo "governor binary sha256 abc"
    echo "harness pinned commit deadbeef, blob cafe"
    echo "producer binary path /p"; echo "producer binary sha256 def"
    echo "producer serving at start $SERV_OK"
    echo "subject HEAD $X"; echo "subject tree fe43d48"; echo "plan sha256 990090fd"; } > "$R/C5.run"
  cp "$W/c1.txt" "$R/C5.subject.start.txt"; echo '{}' > "$R/C5.graph.metadata.pre.json"
  echo "cloning into ..." > "$R/C5.materialise.txt"; }
mk_end() { mk_start; cp "$W/c1.txt" "$R/C5.subject.end.txt"; echo log > "$R/C5.log"; : > "$R/C5.receipts.jsonl"
  echo "task id task-1" > "$R/C5.extract.txt"
  { echo "governor commit at end $X"; echo "governor binary path at end /g"; echo "governor binary sha256 at end abc"
    echo "producer binary path at end /p"; echo "producer binary sha256 at end def"
    echo "producer serving at end $SERV_OK"; echo "producer serving stable yes"
    echo "subject HEAD at end $X"; echo "subject tree at end fe43d48"
    echo "reviewer attempts 4"; echo "reviewer providers attempted codex, gemini"
    echo "reviewer provider gemini"; echo "reviewer verdict accept"; echo "reviewer reviewed digest b4f471f0"
    echo "candidate ref refs/heads/sensei-code/task-1"; echo "candidate head abc123"
    echo "candidate parent $X"; echo "candidate ancestry X->candidate yes"
    echo "candidate-shaped refs in subject 1"
    echo "candidate committed yes"; echo "candidate state exists yes"; echo "EXIT 0"; } >> "$R/C5.run"; }
# a candidate that exists but was never committed -- C4's actual end state
mk_end_uncommitted() { mk_end
  sed -i "s|^candidate committed yes|candidate committed no|" "$R/C5.run"
  sed -i "s|^candidate ancestry X->candidate yes|candidate ancestry X->candidate no|" "$R/C5.run"
  rm -f "$R/C5.candidate.diff"; }

mk_start; check G1 0 "complete start set" bash "$CLO" "$R" start
mk_start; sed -i "s|^subject tree fe43d48|subject tree |" "$R/C5.run"
          check G2 1 "field label present, VALUE empty" bash "$CLO" "$R" start
mk_start; grep -v '^plan sha256' "$R/C5.run" > "$R/t" && mv "$R/t" "$R/C5.run"
          check G3 1 "required field missing entirely" bash "$CLO" "$R" start
mk_start; cp "$W/c7.txt" "$R/C5.subject.start.txt"
          check G4 1 "the start capture carries a FALSIFIER row" bash "$CLO" "$R" start
mk_start; sed -i "s|^producer serving at start .*|producer serving at start pid unknown \| exe unknown \| sha256 unknown|" "$R/C5.run"
          check G5 1 "the serving producer is 'unknown' -- unmeasured, not measured" bash "$CLO" "$R" start
mk_start; grep -v '^harness pinned' "$R/C5.run" > "$R/t" && mv "$R/t" "$R/C5.run"
          check G6 1 "no harness-pinning field" bash "$CLO" "$R" start
mk_end;   check G7 1 "candidate committed yes but no C5.candidate.diff" bash "$CLO" "$R" end
mk_end;   echo diff > "$R/C5.candidate.diff"; check G8 0 "the conditional artifact is present" bash "$CLO" "$R" end
mk_end;   echo diff > "$R/C5.candidate.diff"
          sed -i "s|^producer serving stable yes|producer serving stable no -- start aa end bb|" "$R/C5.run"
          check G9 1 "the serving producer changed across the run" bash "$CLO" "$R" end
mk_end;   echo diff > "$R/C5.candidate.diff"
          grep -v '^reviewer providers attempted' "$R/C5.run" > "$R/t" && mv "$R/t" "$R/C5.run"
          check G10 1 "no record of which providers were attempted" bash "$CLO" "$R" end
mk_start; rm -f "$R/C5.materialise.txt"
          check G13 1 "the materialisation transcript is missing (frozen REQUIRED, previously unchecked)" bash "$CLO" "$R" start
mk_end;   echo diff > "$R/C5.candidate.diff"; rm -f "$R/C5.extract.txt"
          check G14 1 "the extraction record is missing (frozen REQUIRED, previously unchecked)" bash "$CLO" "$R" end
mk_end_uncommitted
          check G15 1 "an UNCOMMITTED candidate state exists and its diff is absent" bash "$CLO" "$R" end
mk_end_uncommitted; echo diff > "$R/C5.candidate.diff"
          check G16 0 "an uncommitted candidate state with its diff preserved" bash "$CLO" "$R" end
mk_end_uncommitted; : > "$R/C5.candidate.diff"
          check G17 1 "the candidate diff is EMPTY with no recorded reason" bash "$CLO" "$R" end
mk_end_uncommitted; : > "$R/C5.candidate.diff"
          echo "candidate diff empty because the candidate state carried no change against X" >> "$R/C5.run"
          check G18 0 "an empty candidate diff with the reason recorded" bash "$CLO" "$R" end
mk_end;   echo diff > "$R/C5.candidate.diff"; sed -i "s|^candidate state exists yes|candidate state exists no|" "$R/C5.run"
          check G19 1 "candidate-shaped refs exist but the run reports no candidate state" bash "$CLO" "$R" end
mk_end;   echo diff > "$R/C5.candidate.diff"; check G11 1 "closed phase with no C5.closure.txt receipt" bash "$CLO" "$R" closed
mk_end;   echo diff > "$R/C5.candidate.diff"
          printf 'instrument closure OK (start)\ninstrument closure OK (end)\n' > "$R/C5.closure.txt"
          check G12 0 "closed phase with both receipts recorded" bash "$CLO" "$R" closed

echo >> "$OUT"; echo "== extractor cases (obligation 6) ==" >> "$OUT"
E="$W/extract"; mkdir -p "$E"
cat > "$E/fallback.jsonl" <<'LOG'
{"kind":"task.created","task_id":"task-42","summary":"t"}
{"kind":"agent.role.assigned","summary":"Codex takes the reviewer role","payload":{"role":"reviewer","provider":"codex","review_attempt":1}}
{"kind":"review.started","summary":"review 1","payload":{"review_attempt":1}}
{"kind":"agent.finished","summary":"codex delivered nothing","payload":{"provider":"codex","error":"no response"}}
{"kind":"agent.role.assigned","summary":"Gemini takes the reviewer role","payload":{"role":"reviewer","provider":"gemini","review_attempt":2}}
{"kind":"review.completed","summary":"ACCEPT","payload":{"decision":"accept","provenance":{"provider":"gemini","candidate_digest":"dd11"}}}
LOG
{ echo "E1 failed provider -> successful fallback provider, both preserved:"
  python3 "$HERE/c5-extract.py" "$E/fallback.jsonl" "$E/r1.jsonl" | sed 's/^/    /'; } >> "$OUT" 2>&1
E1=$(python3 "$HERE/c5-extract.py" "$E/fallback.jsonl" "$E/r1.jsonl")
N=$((N+1))
if grep -q "^reviewer providers attempted codex, gemini$" <<<"$E1" \
   && grep -q "^reviewer provider gemini$" <<<"$E1" \
   && grep -q "codex" <<<"$(sed -n '/reviewer trail:/,$p' <<<"$E1")"; then
  PASS=$((PASS+1)); echo "PASS  E1  both the failed provider and the delivering provider are preserved" >> "$OUT"
else FAIL=$((FAIL+1)); echo "FAIL  E1  the fallback attempt was lost" >> "$OUT"; fi
grep -v 'review.completed' "$E/fallback.jsonl" > "$E/noverdict.jsonl"
E2=$(python3 "$HERE/c5-extract.py" "$E/noverdict.jsonl" "$E/r2.jsonl")
N=$((N+1))
if grep -q "UNREVIEWED" <<<"$E2"; then PASS=$((PASS+1)); echo "PASS  E2  no bounded verdict reads UNREVIEWED, never clean by exhaustion" >> "$OUT"
else FAIL=$((FAIL+1)); echo "FAIL  E2  a missing verdict did not read UNREVIEWED" >> "$OUT"; fi

echo >> "$OUT"; echo "== runner cases (harness pinning) ==" >> "$OUT"
# The runner must refuse a drifted harness BEFORE it materialises a subject.
cp "$HERE/c5-capture.sh" "$W/capture.orig"
trap 'cp "$W/capture.orig" "$HERE/c5-capture.sh"' EXIT
echo "# drift introduced by c5-validate.sh" >> "$HERE/c5-capture.sh"
R1OUT=$(bash "$HERE/c5-run.sh" "$W/never" 2>&1); R1RC=$?
cp "$W/capture.orig" "$HERE/c5-capture.sh"
N=$((N+1))
if [ $R1RC -ne 0 ] && grep -q "harness drift" <<<"$R1OUT" && [ ! -e "$W/never" ]; then
  PASS=$((PASS+1)); echo "PASS  R1  an edited capture script is refused before any subject is materialised" >> "$OUT"
else
  FAIL=$((FAIL+1)); echo "FAIL  R1  a drifted harness was not refused (rc=$R1RC): $R1OUT" >> "$OUT"
fi

{ echo; echo "cases run $N   passed $PASS   failed $FAIL"
  if [ "$FAIL" -eq 0 ]; then echo "PRE-RUN VALIDATION: PASS"
  else echo "PRE-RUN VALIDATION: FAILED -- the harness is not ready and C5 must not run"; fi
  echo
  echo "This validates that the INSTRUMENT REFUSES. It is not a witness and says"
  echo "nothing about whether the governed loop works."; } >> "$OUT"
tail -6 "$OUT"
[ "$FAIL" -eq 0 ]
